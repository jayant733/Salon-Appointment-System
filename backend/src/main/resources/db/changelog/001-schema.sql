-- Initiales PostgreSQL-Datenbankschema
-- ============================================================


-- ============================================================
-- Interne Benutzerkonten
-- ============================================================

CREATE TABLE app_user
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_app_user
        PRIMARY KEY (id),

    CONSTRAINT uk_app_user_email
        UNIQUE (email),

    CONSTRAINT ck_app_user_role
        CHECK (role IN ('EMPLOYEE', 'ADMIN'))
);


-- ============================================================
-- Kunden
-- ============================================================

CREATE TABLE customer
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(40),
    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP WITH TIME ZONE
                           NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_customer
        PRIMARY KEY (id),

    CONSTRAINT uk_customer_email
        UNIQUE (email)
);


-- ============================================================
-- Mitarbeiter
-- ============================================================

CREATE TABLE employee
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(150) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    user_id BIGINT,

    created_at TIMESTAMP WITH TIME ZONE
                           NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_employee
        PRIMARY KEY (id),

    CONSTRAINT uk_employee_email
        UNIQUE (email),

    CONSTRAINT uk_employee_user
        UNIQUE (user_id),

    CONSTRAINT fk_employee_user
        FOREIGN KEY (user_id)
            REFERENCES app_user (id)
            ON UPDATE RESTRICT
            ON DELETE SET NULL
);


-- ============================================================
-- Salonleistungen
-- ============================================================

CREATE TABLE salon_service
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    duration_minutes INTEGER NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_salon_service
        PRIMARY KEY (id),

    CONSTRAINT uk_salon_service_name
        UNIQUE (name),

    CONSTRAINT ck_salon_service_duration
        CHECK (
            duration_minutes >= 5
                AND duration_minutes <= 480
            ),

    CONSTRAINT ck_salon_service_price
        CHECK (price >= 0)
);


-- ============================================================
-- Termine
-- ============================================================

CREATE TABLE appointment
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    customer_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    created_by_user_id BIGINT,

    start_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'BOOKED',
    note VARCHAR(1000),

    cancel_reason VARCHAR(1000),
    cancelled_at TIMESTAMP WITH TIME ZONE,

    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_appointment
        PRIMARY KEY (id),

    CONSTRAINT fk_appointment_customer
        FOREIGN KEY (customer_id)
            REFERENCES customer (id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

    CONSTRAINT fk_appointment_employee
        FOREIGN KEY (employee_id)
            REFERENCES employee (id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

    CONSTRAINT fk_appointment_service
        FOREIGN KEY (service_id)
            REFERENCES salon_service (id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

    CONSTRAINT fk_appointment_created_by_user
        FOREIGN KEY (created_by_user_id)
            REFERENCES app_user (id)
            ON UPDATE RESTRICT
            ON DELETE SET NULL,

    CONSTRAINT ck_appointment_status
        CHECK (
            status IN (
                       'BOOKED',
                       'CONFIRMED',
                       'COMPLETED',
                       'CANCELLED'
                )
            ),

    CONSTRAINT ck_appointment_time
        CHECK (end_time > start_time),

    CONSTRAINT ck_appointment_version
        CHECK (version >= 0)
);